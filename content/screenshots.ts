/**
 * Screenshot manifest — the single source of truth for every image the docs
 * reference.
 *
 * Two consumers read this file, which is why it exists at all:
 *
 *   1. `<Screenshot id="…" />` (components/ui/screenshot.tsx) renders the
 *      image when the file is present under `public/screenshots/`, and a
 *      placeholder carrying `what` + `state` when it is not.
 *   2. `scripts/build-screenshot-index.mjs` emits `docs/screenshot-index.xlsx`
 *      — the capture worklist.
 *
 * Every entry here has its file on disk: the Playwright suite fails on a
 * referenced screenshot without a file, so a page never ships with a
 * "Screenshot pending" placeholder. The set was recaptured on 2026-11-05 on
 * Windows at 200 % from product `main` at 5e54979, using the extended capture
 * tool.
 *
 * SolarLayout Desktop has a single visual theme, so there is exactly ONE
 * image per entry — no light/dark pairs.
 *
 * `priority` records how essential the image is to its page:
 *   1 — essential; the page does not make sense without it
 *   2 — valuable; explains something the prose can only describe
 *   3 — nice to have; polish
 */
export interface ScreenshotSpec {
  /** Stable id used in MDX: `<Screenshot id="…" />`. */
  id: string
  /** Path under `public/screenshots/`. */
  file: string
  /** Docs page that uses it, for the capture worklist. */
  page: string
  /** Short human title — the caption and the worklist row title. */
  title: string
  /** Alt text. Describes the content, not the act of screenshotting. */
  alt: string
  /** What the frame must contain. */
  what: string
  /** How to get the app into that state before capturing. */
  state: string
  /** Callouts to add after capture. Empty string when none. */
  annotations: string
  priority: 1 | 2 | 3
}

